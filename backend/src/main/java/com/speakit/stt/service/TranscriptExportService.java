package com.speakit.stt.service;

import com.speakit.stt.entity.LiveSessionTurn;
import com.speakit.stt.entity.SpeechToTextRequest;
import com.speakit.stt.repository.LiveSessionTurnRepository;
import com.speakit.stt.repository.SpeechToTextRequestRepository;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

import java.util.ArrayList;
import java.util.List;

/**
 * Enterprise Service for exporting STT speech transcriptions and multi-speaker
 * dialogue sessions to standard industry formats: SRT, VTT, Markdown, and plain TXT.
 */
@Service
@RequiredArgsConstructor
@Slf4j
public class TranscriptExportService {

    private final SpeechToTextRequestRepository speechToTextRequestRepository;
    private final LiveSessionTurnRepository liveSessionTurnRepository;

    public String exportTranscript(Long requestId, Long userId, String format) {
        SpeechToTextRequest request = speechToTextRequestRepository.findByIdAndUserId(requestId, userId)
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "Transcription not found"));

        List<LiveSessionTurn> turns = liveSessionTurnRepository.findByRequestIdOrderByTurnIndexAsc(requestId);

        String normalizedFormat = (format != null ? format.trim().toUpperCase() : "TXT");

        return switch (normalizedFormat) {
            case "SRT" -> formatSrt(request, turns);
            case "VTT" -> formatVtt(request, turns);
            case "MARKDOWN", "MD" -> formatMarkdown(request, turns);
            default -> formatTxt(request, turns);
        };
    }

    private String formatTxt(SpeechToTextRequest request, List<LiveSessionTurn> turns) {
        if (turns != null && !turns.isEmpty()) {
            StringBuilder sb = new StringBuilder();
            for (LiveSessionTurn turn : turns) {
                String name = (turn.getSpeakerName() != null && !turn.getSpeakerName().isBlank())
                        ? turn.getSpeakerName()
                        : "Speaker " + (turn.getTurnIndex() + 1);
                sb.append("[").append(name).append("]: ").append(turn.getOriginalText()).append("\n\n");
            }
            return sb.toString().trim();
        }
        return request.getTranscript() != null ? request.getTranscript().trim() : "";
    }

    private String formatMarkdown(SpeechToTextRequest request, List<LiveSessionTurn> turns) {
        StringBuilder sb = new StringBuilder();
        sb.append("# SpeakIT Transcription\n\n");
        sb.append("> **Generated by SpeakIT AI Voice Platform**\n\n");
        sb.append("### Metadata\n");
        if (request.getLanguage() != null) sb.append("- **Language:** ").append(request.getLanguage()).append("\n");
        if (request.getAudioDurationSeconds() != null) sb.append("- **Duration:** ").append(request.getAudioDurationSeconds()).append("s\n");
        if (request.getTranscriptLength() != null) sb.append("- **Characters:** ").append(request.getTranscriptLength()).append("\n");
        if (request.getProvider() != null) sb.append("- **Engine:** ").append(request.getProvider()).append("\n");
        sb.append("\n---\n\n### Transcript\n\n");

        if (turns != null && !turns.isEmpty()) {
            for (LiveSessionTurn turn : turns) {
                String name = (turn.getSpeakerName() != null && !turn.getSpeakerName().isBlank())
                        ? turn.getSpeakerName()
                        : "Speaker " + (turn.getTurnIndex() + 1);
                sb.append("**").append(name).append(":** ").append(turn.getOriginalText()).append("\n\n");
            }
        } else if (request.getTranscript() != null) {
            sb.append(request.getTranscript().trim()).append("\n");
        }
        return sb.toString().trim();
    }

    private String formatSrt(SpeechToTextRequest request, List<LiveSessionTurn> turns) {
        List<Cue> cues = buildCues(request, turns);
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < cues.size(); i++) {
            Cue cue = cues.get(i);
            sb.append(i + 1).append("\n");
            sb.append(formatSrtTime(cue.startMs)).append(" --> ").append(formatSrtTime(cue.endMs)).append("\n");
            sb.append(cue.text).append("\n\n");
        }
        return sb.toString().trim();
    }

    private String formatVtt(SpeechToTextRequest request, List<LiveSessionTurn> turns) {
        List<Cue> cues = buildCues(request, turns);
        StringBuilder sb = new StringBuilder("WEBVTT\n\n");
        for (int i = 0; i < cues.size(); i++) {
            Cue cue = cues.get(i);
            sb.append(i + 1).append("\n");
            sb.append(formatVttTime(cue.startMs)).append(" --> ").append(formatVttTime(cue.endMs)).append("\n");
            if (cue.speaker != null && !cue.speaker.isBlank()) {
                sb.append("<v ").append(cue.speaker).append(">").append(cue.rawText != null ? cue.rawText : cue.text).append("\n\n");
            } else {
                sb.append(cue.text).append("\n\n");
            }
        }
        return sb.toString().trim();
    }

    private record Cue(long startMs, long endMs, String speaker, String rawText, String text) {}

    private List<Cue> buildCues(SpeechToTextRequest request, List<LiveSessionTurn> turns) {
        List<Cue> cues = new ArrayList<>();
        int totalDurationSeconds = (request.getAudioDurationSeconds() != null && request.getAudioDurationSeconds() > 0)
                ? request.getAudioDurationSeconds()
                : 10;
        long totalMs = totalDurationSeconds * 1000L;

        if (turns != null && !turns.isEmpty()) {
            long turnDurationMs = Math.max(1000L, totalMs / turns.size());
            for (int i = 0; i < turns.size(); i++) {
                LiveSessionTurn turn = turns.get(i);
                long start = i * turnDurationMs;
                long end = Math.min(totalMs, (i + 1) * turnDurationMs);
                if (start >= end) end = start + 2000L;
                String speaker = turn.getSpeakerName() != null ? turn.getSpeakerName() : "Speaker";
                String display = "[" + speaker + "]: " + turn.getOriginalText();
                cues.add(new Cue(start, end, speaker, turn.getOriginalText(), display));
            }
        } else {
            String transcript = request.getTranscript() != null ? request.getTranscript().trim() : "";
            cues.add(new Cue(0, totalMs, null, transcript, transcript));
        }
        return cues;
    }

    private String formatSrtTime(long ms) {
        long hours = ms / 3600000;
        long minutes = (ms % 3600000) / 60000;
        long seconds = (ms % 60000) / 1000;
        long millis = ms % 1000;
        return String.format("%02d:%02d:%02d,%03d", hours, minutes, seconds, millis);
    }

    private String formatVttTime(long ms) {
        long hours = ms / 3600000;
        long minutes = (ms % 3600000) / 60000;
        long seconds = (ms % 60000) / 1000;
        long millis = ms % 1000;
        return String.format("%02d:%02d:%02d.%03d", hours, minutes, seconds, millis);
    }
}
